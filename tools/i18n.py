"""i18n helper.

1. Extracts English copy from data-i18n / data-i18n-html / data-i18n-attr in the HTML pages
   into js/locales/en.static.js (the HTML stays the no-JS fallback, so English is written once).
2. Checks that every other locale has exactly the keys English has, and that literal
   t('...') keys used in the scripts exist.

Usage:  python tools/i18n.py
"""
import glob
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
LOCALES = ['de', 'uk']

static = {}
problems = []


def put(key, value, where):
    value = re.sub(r'\s+', ' ', value).strip()
    if key in static and static[key] != value:
        problems.append(f'{where}: "{key}" differs from an earlier page')
    static[key] = value


for page in sorted(glob.glob('*.html')):
    src = open(page, encoding='utf-8').read()
    for m in re.finditer(r'<(\w+)\b([^>]*?)\sdata-i18n="([^"]+)"([^>]*)>(.*?)</\1>', src, re.S):
        text = re.sub(r'<[^>]+>', '', m.group(5))
        put(m.group(3), html.unescape(text), page)
    for m in re.finditer(r'<(\w+)\b([^>]*?)\sdata-i18n-html="([^"]+)"([^>]*)>(.*?)</\1>', src, re.S):
        put(m.group(3), m.group(5), page)
    for m in re.finditer(r'<\w+\b[^>]*\sdata-i18n-attr="([^"]+)"[^>]*>', src):
        tag = m.group(0)
        for pair in m.group(1).split(';'):
            attr, key = [s.strip() for s in pair.split(':')]
            val = re.search(r'\s' + re.escape(attr) + r'="([^"]*)"', tag)
            if not val:
                problems.append(f'{page}: no {attr}="" fallback for {key}')
                continue
            put(key, html.unescape(val.group(1)), page)

with open('js/locales/en.static.js', 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/i18n.py from the HTML pages — do not edit by hand.\n')
    f.write('export default ' + json.dumps(static, ensure_ascii=False, indent=2) + ';\n')


def keys_of(path):
    src = open(path, encoding='utf-8').read()
    return set(re.findall(r"^\s*'([\w.]+)':", src, re.M)) | set(re.findall(r'^\s*"([\w.]+)":', src, re.M))


en_keys = keys_of('js/locales/en.js') | set(static)
for loc in LOCALES:
    path = f'js/locales/{loc}.js'
    if not os.path.exists(path):
        problems.append(f'{path} is missing')
        continue
    k = keys_of(path)
    for miss in sorted(en_keys - k):
        problems.append(f'{loc}: missing {miss}')
    for extra in sorted(k - en_keys):
        problems.append(f'{loc}: unknown key {extra}')

for js in glob.glob('js/*.js'):
    for key in re.findall(r"\bt\('([\w.]+)'", open(js, encoding='utf-8').read()):
        if key not in en_keys:
            problems.append(f'{js}: t("{key}") has no English text')

print(f'{len(static)} static keys, {len(en_keys)} keys in total')
for p in problems:
    print(' -', p)
sys.exit(1 if problems else 0)
